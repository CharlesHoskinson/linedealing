#!/usr/bin/env python3
"""Write the Audit module of one capability package.

The Audit module pins `#print axioms` of every theorem of the spec library and
`#audit_ns NS` at `[]`, each with `#guard_msgs`, so a new axiom, `sorryAx` or a
`_native` axiom fails `lake build --wfail` (formal plugin, practices 38 to 40).

The script lists the theorems of the package's modules, runs `#print axioms` on
each through `lake env lean`, and refuses to write the module if any theorem
depends on an axiom outside the allowlist `propext`, `Classical.choice`,
`Quot.sound`. Run it after a change that adds or renames a theorem; the build
then checks the pins.

usage: gen_audit.py PACKAGE_DIR NAMESPACE MODULE...   (modules without the namespace dir, e.g. Spec Tests)
"""
import pathlib, re, subprocess, sys, tempfile

ALLOW = {"propext", "Classical.choice", "Quot.sound"}

def main():
    pkg = pathlib.Path(sys.argv[1]).resolve()
    ns = sys.argv[2]
    mods = sys.argv[3:]
    names = []
    for m in mods:
        text = (pkg / ns / f"{m}.lean").read_text()
        text = re.sub(r"/-.*?-/", "", text, flags=re.S)
        names += [n for n in re.findall(r"^theorem\s+([A-Za-z0-9_'.]+)", text, flags=re.M)]
    imports = "\n".join(f"import {ns}.{m}" for m in mods)
    body = "\n".join(f"#print axioms {ns}.{n}" for n in names)
    with tempfile.NamedTemporaryFile("w", suffix=".lean", dir=pkg, delete=False) as f:
        f.write(imports + "\n" + body + "\n")
        tmp = pathlib.Path(f.name)
    try:
        r = subprocess.run(["lake", "env", "lean", str(tmp)], cwd=pkg, capture_output=True, text=True)
    finally:
        tmp.unlink()
    out = r.stdout + r.stderr
    if r.returncode != 0:
        sys.exit(f"gen_audit: lean failed:\n{out[-3000:]}")
    # one message per theorem; a message starts with the quoted theorem name
    msgs = re.findall(r"^('" + re.escape(ns) + r"\.[^']*' (?:depends on axioms: \[[^\]]*\]|does not depend on any axioms))",
                      out, flags=re.M | re.S)
    if len(msgs) != len(names):
        sys.exit(f"gen_audit: {len(names)} theorems, {len(msgs)} messages:\n{out[-3000:]}")
    blocks = []
    bad = []
    for n, m in zip(names, msgs):
        m = " ".join(m.split())
        ax = re.search(r"depends on axioms: \[(.*)\]", m)
        if ax:
            used = {a.strip() for a in ax.group(1).split(",")}
            if used - ALLOW:
                bad.append(f"{n}: {sorted(used - ALLOW)}")
        elif "does not depend on any axioms" not in m:
            bad.append(f"{n}: {m}")
        blocks.append(f"/-- info: {m} -/\n#guard_msgs in\n#print axioms {ns}.{n}\n")
    if bad:
        sys.exit("gen_audit: axioms outside the allowlist:\n" + "\n".join(bad))
    head = f"""import SplitCodec.AuditCmd
{imports}

/-!
# Audit

Generated by `../scripts/gen_audit.py`; the build checks every pin.

* `#audit_ns {ns}` lists every `implemented_by`, `extern`, `csimp`, `unsafe`,
  `partial`, `partial_fixpoint`, `opaque` and `axiom` declaration of the
  namespace and of its modules. It is pinned at `[]`.
* `#print axioms` of each theorem, pinned. Only `propext`, `Classical.choice`
  and `Quot.sound` occur; the generator refuses any other axiom.

`Main` does not import this module, so `import Lean` here does not change the
oracle binary.
-/

/-- info: [] -/
#guard_msgs in
#audit_ns {ns}

"""
    (pkg / ns / "Audit.lean").write_text(head + "\n".join(blocks))
    print(f"gen_audit: {len(names)} theorems pinned in {ns}/Audit.lean")

main()
