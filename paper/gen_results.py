#!/usr/bin/env python3
"""Regenerate results.tex from ../impl/BENCHMARKS.md.

Usage: python3 gen_results.py > results.tex
Every measured number of the paper is a macro in results.tex. The tables of
BENCHMARKS.md are parsed; the figures that BENCHMARKS.md gives only in prose
are in PROSE below and must be edited by hand after a rerun.
"""
import re, sys, pathlib

SRC = pathlib.Path(__file__).resolve().parent.parent / "impl" / "BENCHMARKS.md"

# Figures stated in the prose of BENCHMARKS.md (not in a table).
PROSE = {
    "nineQuorumMeasured": "6",        # quorum used by the n = 9 measurement
    "ninePostCheckMicros": "54",      # one post-signature check, microseconds
    "ninePostSharePct": "49",         # share of per-node CPU spent on post checks, t = f+1
    "nineNodeRateLow": "5,200",       # requests/s, 16-core node at 80% use, t = 3
    "nineNodeRateHigh": "3,700",      # same, t = 7
    "nineNodeCores": "16",
    "nineNodeUsePct": "80",
    "nineBatchedRate": "770",       # requests/s per core if the board certifies posts in batches
    "ninePartialMinMicros": "200",    # partial / verify_partial range at n = 9
    "ninePartialMaxMicros": "420",
    "implTestsPassed": "91",
    "simRuns": "72",
    "simRequests": "16",
    "simSignatures": "1,152",
    "simBoardIntervalMs": "1",
    "simQuorum": "6",
    "simServiceOpenSingle": "27.8",   # derived service bound, single-post batches, open
    "simServiceOpenBatch": "444.4",   # derived service bound, batches of 16, open
    "commitSeconds": "0.5",           # assumed board commit time for the latency example
    "latencySeconds": "1.5",          # three commits at commitSeconds
    "nineMsgBytesMeasuredLow": "1,461",   # prototype message, 130-byte proof, t = 3
    "nineMsgBytesMeasuredHigh": "1,725",  # same, t = 7
}

SUITE = {"ecdsa": "Ecdsa", "bip340": "Bip", "ed25519": "Ed"}
MODE = {"open": "Open", "sealed-k8": "Sealed"}
NNAME = {9: "Nine", 16: "Sixteen", 64: "SixtyFour", 256: "TwoFiveSix"}
COLS = ["Owner", "StepA", "Decrypt", "Partial", "Verify", "Combine"]
LOWT = {9: 3, 16: 6, 64: 22, 256: 86}


def ms(us):
    v = float(us.replace(",", "")) / 1000.0
    return f"{v:.2f}" if v < 100 else f"{v:.1f}"


def cells(line):
    return [c.strip().strip("*") for c in line.strip().strip("|").split("|")]


def main():
    text = SRC.read_text().splitlines()
    out = ["% Refreshed 2026-11-14 from the final runs (q quorums, 196-byte proof).",
           "% Generated by gen_results.py from impl/BENCHMARKS.md. Macro names use letters only.",
           "% Microbenchmark macros are in milliseconds."]
    out.append("% --- figures from the prose of BENCHMARKS.md")
    for k, v in PROSE.items():
        out.append(f"\\newcommand{{\\{k}}}{{{v}}}")
    out.append("% --- microbenchmarks: \\bm<Suite><Mode><N><T><Step>, ms")
    seen = set()
    for line in text:
        c = cells(line)
        if len(c) == 9 and c[0] in SUITE:          # nine-node table
            suite, mode, n, t, vals = c[0], c[1], 9, int(c[2]), c[3:]
        elif len(c) == 10 and c[0] in SUITE:       # larger committees
            suite, mode, n, t, vals = c[0], c[1], int(c[2]), int(c[3]), c[4:]
        else:
            continue
        tn = "Low" if t == LOWT[n] else "High"
        for col, v in zip(COLS, vals):
            name = f"bm{SUITE[suite]}{MODE[mode]}{NNAME[n]}{tn}{col}"
            assert name not in seen, name
            seen.add(name)
            out.append(f"\\newcommand{{\\{name}}}{{{ms(v)}}}")
    out.append("% --- hand-timed per-request cost, open ECDSA, one slot (bench9)")
    for line in text:
        c = cells(line)
        if len(c) == 8 and c[0] == "n=9, f=2":   # Committee | q | t | bytes | posts | node | combiner | rate
            tn = "Low" if c[2] == "3" else "High"
            for key, v in zip(["PostChecks", "NodeMicros", "CombinerMicros", "ReqPerCore"], c[4:]):
                out.append(f"\\newcommand{{\\nine{key}{tn}}}{{{v}}}")
    out.append("% --- committee simulation, n = 9, 16 requests: \\sim<Suite><Mode><T><PFifty|Rate>")
    sims = {"ECDSA": "Ecdsa", "BIP340": "Bip", "Ed25519": "Ed"}
    for line in text:
        c = cells(line)
        if len(c) == 6 and c[0] in sims:
            tn = "Low" if c[2] == "3" else "High"
            base = f"sim{sims[c[0]]}{MODE[c[1]]}{tn}"
            out.append(f"\\newcommand{{\\{base}PFifty}}{{{float(c[3]):.0f}}}")
            out.append(f"\\newcommand{{\\{base}Rate}}{{{float(c[5]):.0f}}}")
    out.append("% --- open ECDSA simulation by link delay and batch size: \\simLink<T><Delay><Batch><PFifty|Rate>")
    dn = {"0": "Zero", "25": "TwentyFive", "50": "Fifty"}
    bn = {"1": "One", "16": "Sixteen"}
    for line in text:
        c = cells(line)
        if len(c) == 6 and c[0] in ("3", "7") and c[1] in dn and c[2] in bn:
            tn = "Low" if c[0] == "3" else "High"
            base = f"simLink{tn}{dn[c[1]]}{bn[c[2]]}"
            out.append(f"\\newcommand{{\\{base}PFifty}}{{{float(c[3]):.0f}}}")
            out.append(f"\\newcommand{{\\{base}Rate}}{{{float(c[5]):.0f}}}")
    print("\n".join(out))


if __name__ == "__main__":
    main()
